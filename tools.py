def render_spectrogram_png(audio_file_id: str) -> Path:
    """
    Render (or reuse a cached) mel spectrogram PNG for an uploaded file.

    Column k of the image covers [k/W * D, (k+1)/W * D) seconds, so the image's
    left edge is 0 s and its right edge is the full duration D. Low
    frequencies are at the bottom. Not an LLM tool.
    """
    file_path = resolve_uploaded_audio(audio_file_id)

    cache_path = SPECTROGRAM_CACHE_DIR / (
        f"{file_path.stem}_{SPECTROGRAM_CACHE_VERSION}.png"
    )

    if cache_path.is_file():
        return cache_path

    import matplotlib

    matplotlib.use("Agg")

    from matplotlib.colors import LinearSegmentedColormap
    from matplotlib.image import imsave

    y, sr = librosa.load(str(file_path), sr=22050, mono=True)

    if len(y) == 0:
        raise ValueError("The uploaded audio file contains no audio samples.")

    duration = len(y) / sr
    _AUDIO_DURATION_CACHE[file_path.name] = duration

    hop_length = 512

    mel = librosa.feature.melspectrogram(
        y=y,
        sr=sr,
        n_fft=2048,
        hop_length=hop_length,
        n_mels=SPECTROGRAM_MEL_BANDS,
        fmax=sr / 2,
    )

    mel_db = librosa.power_to_db(mel, ref=np.max, top_db=80.0)
    normalized = np.clip((mel_db + 80.0) / 80.0, 0.0, 1.0)

    frame_times = librosa.frames_to_time(
        np.arange(normalized.shape[1]),
        sr=sr,
        hop_length=hop_length,
    )

    width = SPECTROGRAM_WIDTH_PX
    edges = np.linspace(0.0, duration, width + 1)
    first_frames = np.searchsorted(frame_times, edges[:-1], side="left")
    last_frames = np.searchsorted(frame_times, edges[1:], side="left")

    image = np.empty((normalized.shape[0], width), dtype=np.float32)
    max_frame = normalized.shape[1] - 1

    for column in range(width):
        first = first_frames[column]
        last = last_frames[column]

        if last > first:
            image[:, column] = normalized[:, first:last].mean(axis=1)
        else:
            # Short files: more columns than frames, so use the nearest frame.
            center = (edges[column] + edges[column + 1]) / 2
            nearest = int(round(center * sr / hop_length))
            image[:, column] = normalized[:, min(max(nearest, 0), max_frame)]

    colormap = LinearSegmentedColormap.from_list(
        "studio_copilot",
        SPECTROGRAM_COLORS,
    )

    temp_path = cache_path.with_name(
        f"{cache_path.stem}.{os.getpid()}.{time.monotonic_ns()}.tmp.png"
    )

    try:
        imsave(
            temp_path,
            image,
            cmap=colormap,
            vmin=0.0,
            vmax=1.0,
            origin="lower",
            format="png",
        )
        os.replace(temp_path, cache_path)
    finally:
        temp_path.unlink(missing_ok=True)

    return cache_path


