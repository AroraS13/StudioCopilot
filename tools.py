def resolve_uploaded_audio(audio_file_id: str) -> Path:
    """Return the path of an uploaded audio file.

    Raises ValueError for a malformed ID and FileNotFoundError when the file
    is not present in the upload directory.
    """
    if not isinstance(audio_file_id, str) or not AUDIO_FILE_ID_PATTERN.fullmatch(audio_file_id):
        raise ValueError("Invalid audio file ID.")

    file_path = AUDIO_UPLOAD_DIR / audio_file_id

    if not file_path.is_file():
        raise FileNotFoundError("The uploaded audio file could not be found.")

    return file_path


def get_audio_duration(file_path: Path) -> float:
    """Duration in seconds of an uploaded audio file, cached per file."""
    key = file_path.name

    if key not in _AUDIO_DURATION_CACHE:
        _AUDIO_DURATION_CACHE[key] = float(librosa.get_duration(path=str(file_path)))

    return _AUDIO_DURATION_CACHE[key]

